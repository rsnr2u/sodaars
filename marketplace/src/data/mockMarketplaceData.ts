export function getResourcesByCity(cityName: string): MarketplaceResource[] {
  const norm = cityName.toLowerCase();
  return MOCK_MARKETPLACE_RESOURCES.filter(
    (r) => r.location.city.toLowerCase().includes(norm) || norm.includes(r.location.city.toLowerCase())
  );
}

