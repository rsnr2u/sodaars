/**
 * Retrieves all bookings combining saved provider bookings from localStorage
 * with the baseline sample bookings.
 */
export function getAllProviderBookings(): BookingRecord[] {
  try {
    const stored = localStorage.getItem('sodaars_provider_bookings');
    if (stored) {
      const parsed: BookingRecord[] = JSON.parse(stored);
      // Merge unique by id
      const existingIds = new Set(parsed.map((b) => b.id));
      const remaining = SAMPLE_BOOKINGS.filter((b) => !existingIds.has(b.id));
      return [...parsed, ...remaining];
    }
  } catch (e) {
    console.error('Error reading sodaars_provider_bookings:', e);
  }
  return SAMPLE_BOOKINGS;
}

/**
 * Filter bookings belonging to a specific customer either by customerId or matching companyName.
 */
export function getBookingsForCustomer(
  customerId: string,
  companyName: string,
  allBookings: BookingRecord[] = getAllProviderBookings()
): BookingRecord[] {
  const normCompany = companyName.trim().toLowerCase();
  return allBookings.filter((b) => {
    if (b.customerId && b.customerId === customerId) return true;
    if (b.companyName && b.companyName.trim().toLowerCase() === normCompany) return true;
    return false;
  });
}
