export function getAllCampaigns(): CampaignRecord[] {
  try {
    const stored = localStorage.getItem('sodaars_provider_campaigns');
    if (stored) {
      const parsed: CampaignRecord[] = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Storage error reading campaigns:', e);
  }
  return SAMPLE_CAMPAIGNS;
}

export function saveCampaignsToStorage(campaigns: CampaignRecord[]): void {
  try {
    localStorage.setItem('sodaars_provider_campaigns', JSON.stringify(campaigns));
  } catch (e) {
    console.error('Storage error saving campaigns:', e);
  }
}
